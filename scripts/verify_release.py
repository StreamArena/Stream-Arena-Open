"""Check paper values, public display policy and frozen executable source hashes."""
from pathlib import Path
import argparse
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from stream_arena.scoring.leaderboard import public_board, paper_board, markdown  # noqa: E402
from stream_arena.scoring.reporting_identity import roster_summary  # noqa: E402


def require(ok, message):
    if not ok:
        raise ValueError(message)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--freeze', action='store_true', help='Maintainer: refresh executable-file hashes after review')
    args = parser.parse_args()
    paper = json.loads((ROOT/'leaderboard/paper_results.json').read_text())
    board = json.loads((ROOT/'leaderboard/v1_leaderboard.json').read_text())
    public = paper_board(board, paper)
    require(board == public, 'Public results must contain exactly the paper rows, metrics and approved metadata')
    require(not (ROOT/'evaluation/protocol/validation_class_counts.json').exists(),
            'Unpublished calibration counts must stay internal')
    for name in ('results', 'runs', 'recordings', 'leaderboard/diagnostics'):
        require(not (ROOT/name).exists(), f'Internal experimental artifacts in release: {name}')
    count = roster_summary(public['entries'])
    require(count['coreReportedModels'] == 39 and count['coreConfigurations'] == 49, 'Core model/configuration count drift')
    require(count['coreModelIdentifiers'] == 45, 'Registration identity count drift')
    core = {r['systemId']:r for r in public['entries'] if r['population']=='core'}
    from stream_arena.models.registry import systems
    registered = systems()
    require(set(core) <= set(registered), f'Paper configurations missing adapters: {sorted(set(core)-set(registered))}')
    require(set(core) == {r['systemId'] for r in paper['entries']}, 'Paper and public system rosters differ')
    for row in paper['entries']:
        require(registered[row['systemId']]['group'] == row['group'], f"Wrong adapter task: {row['systemId']}")
        for metric, value in row['metrics'].items():
            require(core[row['systemId']]['metrics'][metric]['value'] == value,
                    f"Paper score differs: {row['systemId']}/{metric}")
    require(sum((29 if r['group']=='avatar_performance' else 30)*3 for r in paper['entries']) == 4389,
            'Core run count drift')
    tables = markdown(board)
    require((ROOT/'leaderboard/v1_leaderboard.md').read_text().endswith(tables+'\n'), 'Regenerate the Markdown leaderboard')
    require('| Common-4' in tables and '<u>' not in tables and '**Bold**' not in tables, 'Table policy drift')
    policy = json.loads((ROOT/'evaluation/protocol/evaluation_v2.json').read_text())
    scoring = json.loads((ROOT/'evaluation/protocol/scoring_v2.json').read_text())
    require(policy['aggregation']['table_highlights'] == 'none', 'Machine policy still requests winner marks')
    require(scoring['metrics']['stability']['quality_rating_min'] == 3, 'Stability quality gate differs')
    require(policy['aggregation']['repetitions_per_condition'] == 3, 'Paper repetitions differ')
    require(policy['aggregation']['duration_strata_s'] == [15,30,60,120,300], 'Duration weights differ')
    from stream_arena.judge import prompts
    from stream_arena.judge.av_sync import AV_VERSION
    version = {'visual':prompts.JUDGE_VERSION, 'extension':prompts.EXT_VERSION,
               'stability':prompts.STABILITY_RULE, 'av_sync':AV_VERSION,
               'visual_prompts_sha256':prompts.PROMPTS_SHA256,
               'extension_prompts_sha256':prompts.EXT_PROMPTS_SHA256}
    frozen_path = ROOT/'evaluation/protocol/release_manifest.json'
    sources = [p for base in ('stream_arena','models','examples','evaluation/protocol')
               for p in (ROOT/base).rglob('*') if p.is_file() and p.suffix in ('.py','.json','.mjs','.js','.sh')
               and p != frozen_path and not {'__pycache__', 'node_modules'}.intersection(p.parts)]
    sources += [ROOT/'pyproject.toml', ROOT/'leaderboard/paper_results.json']
    hashes = {str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(sources)}
    manifest = {'schema':'stream-arena.executable-release/1', 'runtime':version,
                'historical_paper_observations':{'visual':'stream-arena.v1-structured-judge/4',
                    'extension':'stream-arena.v1-structured-judge/4-ext/1',
                    'warning':'Historical observations and validation are not regenerated by matching model names. Current runtime requires its own validation.'},
                'files':hashes}
    if args.freeze:
        frozen_path.write_text(json.dumps(manifest,indent=2)+'\n')
    require(frozen_path.exists() and json.loads(frozen_path.read_text()) == manifest,
            'Executable sources changed; review and freeze the release before publishing')
    print(json.dumps({'ok':True,'reported_models':39,'configurations':49,'runs':4389,
                      'frozen_files':len(hashes),'historical_observations_are_not_current_judge_validation':True}))


if __name__ == '__main__':
    main()
